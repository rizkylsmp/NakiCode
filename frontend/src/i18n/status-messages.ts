export function translateSystemStatus(key: string) {
  const failure = key.match(
    /^Gagal (.+?) (.+?)(\. Pastikan backend aktif\.|\. Silakan login ulang\.|\. Coba lagi sebentar\.|\. Pastikan pesanan sudah selesai\.|\.)?$/,
  );
  if (failure && actions[failure[1]] && objects[failure[2]]) {
    const suffix = failure[3]?.includes("backend")
      ? ". Check that the API is available."
      : failure[3]?.includes("login")
        ? ". Sign in again."
        : failure[3]?.includes("sebentar")
          ? ". Please retry shortly."
          : failure[3]?.includes("selesai")
            ? ". Make sure the order is completed."
            : ".";
    return `Could not ${actions[failure[1]]} ${objects[failure[2]]}${suffix}`;
  }
  const loading = key.match(/^Memuat (.+)\.\.\.$/);
  if (loading && objects[loading[1]])
    return `Loading ${objects[loading[1]]}...`;
  const login = key.match(/^Login (admin|user) diperlukan untuk (.+?) (.+)\.$/);
  if (login && actions[login[2]] && objects[login[3]])
    return `${login[1] === "admin" ? "Administrator" : "Client"} sign-in is required to ${actions[login[2]]} ${objects[login[3]]}.`;
  const saved = key.match(
    /^(.+?) berhasil (disimpan|diperbarui|dihapus|dibuat|ditambahkan|diunggah|dimuat|diverifikasi)\.?$/,
  );
  const savedActions: Record<string, string> = {
    disimpan: "saved",
    diperbarui: "updated",
    dihapus: "deleted",
    dibuat: "created",
    ditambahkan: "added",
    diunggah: "uploaded",
    dimuat: "loaded",
    diverifikasi: "verified",
  };
  const savedObjects: Record<string, string> = {
    Kategori: "Category",
    Artikel: "Article",
    Testimonial: "Testimonial",
    "Gambar banner": "Banner image",
    Pengeluaran: "Expense",
    "Profil akun": "Account profile",
    "Nama akun": "Account name",
    Password: "Password",
    Email: "Email",
  };
  if (saved && savedActions[saved[2]] && savedObjects[saved[1]])
    return `${savedObjects[saved[1]]} ${savedActions[saved[2]]}${key.endsWith(".") ? "." : ""}`;
  return null;
}
